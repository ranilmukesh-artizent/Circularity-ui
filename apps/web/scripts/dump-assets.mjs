// Writes src/ui/assets.gen.ts: the demo's static assets (logos, the Lucide icon set, vendor logos and the rules that
// pick a vendor logo), read from index.html run headless. Committed, so the app builds without the demo's script.
// Run again only when index.html's assets change:  node scripts/dump-assets.mjs
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { freshDemo, root } from './golden-sandbox.mjs';

const g = freshDemo();
const LOGO = g('LOGO');
const LOGO_INK = g('LOGO_INK');
const ICON = g('ICON');
const SYSLOGO = g('SYSLOGO');
const LOGO_KEY = g('LOGO_KEY').map(([re, key]) => [re.source, re.flags, key]);

const out = join(root, 'apps/web/src/ui/assets.gen.ts');
const lit = (v) => JSON.stringify(v);
writeFileSync(
  out,
  `// GENERATED by scripts/dump-assets.mjs from index.html. Do not edit.
/* eslint-disable */
export const LOGO: string = ${lit(LOGO)};
export const LOGO_INK: string = ${lit(LOGO_INK)};
export const ICON: Record<string, string> = ${lit(ICON)};
export const SYSLOGO: Record<string, string> = ${lit(SYSLOGO)};
/** Which vendor logo a system name gets: the first pattern that matches. */
export const LOGO_KEY: [RegExp, string][] = (${lit(LOGO_KEY)} as [string, string, string][]).map(([s, f, k]) => [new RegExp(s, f), k]);
`,
);
console.log(`[assets] ${out}: ${Object.keys(ICON).length} icons, ${Object.keys(SYSLOGO).length} vendor logos, ${LOGO_KEY.length} logo rules`);
