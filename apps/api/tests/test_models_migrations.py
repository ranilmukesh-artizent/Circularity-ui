"""di/models.py and the migrations describe the same schema (finding F16).

- `alembic check` against the live database finds nothing to generate: every table the migrations create is declared
  on Base.metadata, with the same columns, types, nullability, keys and indexes.
- The migrations run down to base and up to head again cleanly. That runs on a scratch database created for the
  test (di_migrations_test), never on di.
"""

import pytest
from alembic import command
from alembic.config import Config
from sqlalchemy import create_engine, inspect, text
from sqlalchemy.engine import make_url

import di.models  # noqa: F401  (registers the tables on Base.metadata)
from di.config import get_settings
from di.db import Base, engine

SCRATCH = "di_migrations_test"


def _config(url: str | None = None) -> Config:
    cfg = Config("alembic.ini")
    if url is not None:
        cfg.set_main_option("sqlalchemy.url", url.replace("%", "%%"))
    return cfg


def test_metadata_declares_every_table():
    live = set(inspect(engine).get_table_names()) - {"alembic_version"}
    assert set(Base.metadata.tables) == live


def test_alembic_check_finds_no_differences():
    command.check(_config())  # raises AutogenerateDiffsDetected when the metadata and the database differ


@pytest.fixture
def scratch_url():
    url = make_url(get_settings().database_url)
    admin = create_engine(url.set(database="postgres"), isolation_level="AUTOCOMMIT")
    with admin.connect() as conn:
        conn.execute(text(f"DROP DATABASE IF EXISTS {SCRATCH} WITH (FORCE)"))
        conn.execute(text(f"CREATE DATABASE {SCRATCH}"))
    try:
        yield url.set(database=SCRATCH).render_as_string(hide_password=False)
    finally:
        with admin.connect() as conn:
            conn.execute(text(f"DROP DATABASE IF EXISTS {SCRATCH} WITH (FORCE)"))
        admin.dispose()


def _tables(url: str) -> set[str]:
    eng = create_engine(url)
    try:
        return set(inspect(eng).get_table_names())
    finally:
        eng.dispose()


def test_downgrade_and_upgrade_round_trip(scratch_url):
    assert make_url(scratch_url).database == SCRATCH  # never the live database
    cfg = _config(scratch_url)
    command.upgrade(cfg, "head")
    assert _tables(scratch_url) - {"alembic_version"} == set(Base.metadata.tables)
    command.check(cfg)

    command.downgrade(cfg, "base")
    assert _tables(scratch_url) <= {"alembic_version"}

    command.upgrade(cfg, "head")
    assert _tables(scratch_url) - {"alembic_version"} == set(Base.metadata.tables)
    command.check(cfg)
